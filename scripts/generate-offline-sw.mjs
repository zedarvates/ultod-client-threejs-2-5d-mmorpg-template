import { createHash } from "node:crypto";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const distDir = new URL("../dist/", import.meta.url);
const distPath = distDir.pathname;
const indexPath = join(distPath, "index.html");

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...await walk(full));
    else if (entry.isFile() && entry.name !== "sw.js") files.push(full);
  }
  return files;
}

const registration = `<script type="module">\nif ("serviceWorker" in navigator && window.isSecureContext) {\n  window.addEventListener("load", () => {\n    const swUrl = new URL("./sw.js", document.baseURI);\n    void navigator.serviceWorker.register(swUrl, { scope: "./" });\n  }, { once: true });\n}\n</script>\n`;

const originalIndex = await readFile(indexPath, "utf8");
if (!originalIndex.includes("navigator.serviceWorker.register")) {
  await writeFile(indexPath, originalIndex.replace("</body>", `${registration}</body>`), "utf8");
}

const files = (await walk(distPath)).sort();
const hash = createHash("sha256");
const urls = [];
for (const file of files) {
  const rel = relative(distPath, file).split(sep).join("/");
  const info = await stat(file);
  hash.update(rel);
  hash.update(String(info.size));
  hash.update(await readFile(file));
  urls.push(`./${rel}`);
}

const version = hash.digest("hex").slice(0, 16);
const source = `// Generated by scripts/generate-offline-sw.mjs\nconst CACHE = "ultod-offline-${version}";\nconst PRECACHE = ${JSON.stringify(urls, null, 2)};\n\nself.addEventListener("install", (event) => {\n  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));\n});\n\nself.addEventListener("activate", (event) => {\n  event.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((key) => key.startsWith("ultod-offline-") && key !== CACHE).map((key) => caches.delete(key)))).then(() => self.clients.claim()));\n});\n\nself.addEventListener("fetch", (event) => {\n  const request = event.request;\n  if (request.method !== "GET") return;\n  const url = new URL(request.url);\n  if (url.origin !== self.location.origin) return;\n  event.respondWith(caches.match(request).then((cached) => cached || fetch(request).then((response) => {\n    if (response.ok) {\n      const clone = response.clone();\n      void caches.open(CACHE).then((cache) => cache.put(request, clone));\n    }\n    return response;\n  }).catch(() => request.mode === "navigate" ? caches.match("./index.html") : undefined)));\n});\n`;

await writeFile(join(distPath, "sw.js"), source, "utf8");
console.log(`[offline] generated sw.js with ${urls.length} precached files (${version})`);
